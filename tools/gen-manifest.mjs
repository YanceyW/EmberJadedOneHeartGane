import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const source = path.join(root, 'tools', 'games.manifest.json');
const target = path.join(root, 'src', 'shared', 'content', 'games-manifest.generated.ts');
const loaderTarget = path.join(root, 'src', 'shared', 'content', 'game-loaders.generated.ts');

const manifest = JSON.parse(fs.readFileSync(source, 'utf8').replace(/^\uFEFF/, ''));

const ids = new Set();
for (const game of manifest.games) {
  if (!game.id || ids.has(game.id)) {
    throw new Error(`Invalid or duplicate game id: ${game.id}`);
  }
  ids.add(game.id);
}

const content = `// Generated by tools/gen-manifest.mjs. Do not edit by hand.

export type GameStatus = 'playable' | 'coming-soon';

export interface GameManifestEntry {
  id: string;
  title: string;
  subtitle: string;
  packageName: string;
  root: string;
  status: GameStatus;
  accent: string;
}

export const GAMES: GameManifestEntry[] = ${JSON.stringify(manifest.games, null, 2)};
`;

fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, content, 'utf8');

// 微信小游戏的 require 只接受可静态分析的路径，因此这里为每款游戏生成一条
// 字面量 require；调用仍然发生在 loadSubpackage 成功之后，不会把分包代码打进主包。
const playable = manifest.games.filter((game) => game.status === 'playable');
const loaderEntries = playable
  .map(
    (game) => `  ${JSON.stringify(game.id)}: () => {
    require('../../games/${game.id}/game');
  },`,
  )
  .join('\n');

const loaderContent = `/* eslint-disable @typescript-eslint/no-require-imports */
// Generated by tools/gen-manifest.mjs. Do not edit by hand.

export type GameLoader = () => void;

export const GAME_LOADERS: Record<string, GameLoader> = {
${loaderEntries}
};
`;

fs.writeFileSync(loaderTarget, loaderContent, 'utf8');

console.log(`[manifest] ${manifest.games.length} games -> ${path.relative(root, target)}`);
console.log(`[manifest] ${playable.length} loader(s) -> ${path.relative(root, loaderTarget)}`);
