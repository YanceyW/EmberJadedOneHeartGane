import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const source = path.join(root, 'tools', 'games.manifest.json');
const target = path.join(root, 'src', 'shared', 'content', 'games-manifest.generated.ts');

const manifest = JSON.parse(fs.readFileSync(source, 'utf8').replace(/^\uFEFF/, ''));

const ids = new Set();
for (const game of manifest.games) {
  if (!game.id || ids.has(game.id)) {
    throw new Error(`Invalid or duplicate game id: ${game.id}`);
  }
  ids.add(game.id);
}

const content = `// Generated by tools/gen-manifest.mjs. Do not edit by hand.

export type GameStatus = 'playable' | 'coming-soon';

export interface GameManifestEntry {
  id: string;
  title: string;
  subtitle: string;
  packageName: string;
  root: string;
  status: GameStatus;
  accent: string;
}

export const GAMES: GameManifestEntry[] = ${JSON.stringify(manifest.games, null, 2)};
`;

fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, content, 'utf8');

// 分包根目录的 game.js 是入口，由 wx.loadSubpackage 自动执行并注册 GameDefinition，
// 主包不需要（也不应该）require 分包文件。
const staleLoader = path.join(root, 'src', 'shared', 'content', 'game-loaders.generated.ts');
if (fs.existsSync(staleLoader)) {
  fs.rmSync(staleLoader, { force: true });
  console.log('[manifest] removed legacy game-loaders.generated.ts');
}

console.log(`[manifest] ${manifest.games.length} games -> ${path.relative(root, target)}`);
